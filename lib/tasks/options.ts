import { isRoleId, ROLE_BY_ID } from "../roles";
import type { PlanStatus, TaskStatus } from "./store";

/**
 * Options shared by the task form, the detail page and the server actions.
 * Activity types are deliberately absent: they are master data and come from
 * `listActiveActivityTypes()` (Masters → Activity types).
 */
export const PLAN_STATUS_OPTIONS: { value: PlanStatus; label: string }[] = [
  { value: "planned", label: "Planned" },
  { value: "unplanned", label: "Unplanned" },
];

/**
 * The six workflow states. `hint` is the meaning of the state, shown against
 * the selected status only — it is the definition of the step, not decoration.
 */
export const TASK_STATUS_OPTIONS: { value: TaskStatus; label: string; hint: string }[] = [
  { value: "todo", label: "To Do", hint: "Yet to start." },
  { value: "in_progress", label: "In Progress", hint: "Work has started." },
  { value: "completed", label: "Completed", hint: "The task is done." },
  {
    value: "feedback",
    label: "Feedback",
    hint: "The assignee has finished; the requester has not confirmed it yet.",
  },
  {
    value: "failed",
    label: "Failed",
    hint: "The deployment went live but did not work, so a rollback has started.",
  },
  {
    value: "reopen",
    label: "Reopen",
    hint: "Work reported complete hit a new issue; it comes back to this task.",
  },
];

export const TASK_STATUS_VALUES: TaskStatus[] = TASK_STATUS_OPTIONS.map((option) => option.value);

export const TASK_STATUS_LABEL: Record<TaskStatus, string> = Object.fromEntries(
  TASK_STATUS_OPTIONS.map((option) => [option.value, option.label]),
) as Record<TaskStatus, string>;

/** The definition of a status, for the form and the status panel. */
export function taskStatusHint(status: TaskStatus): string {
  return TASK_STATUS_OPTIONS.find((option) => option.value === status)?.hint ?? "";
}

/** A task is open until it is completed; feedback, failed and reopen are open. */
export function isOpenStatus(status: TaskStatus): boolean {
  return status !== "completed";
}

/** The id is generated by the database sequence, never by the form. */
export const NEXT_TASK_ID_HINT = "Generated on save";

/** Label/value/hint triple the assignee picker consumes. */
export type TaskPersonOption = { value: string; label: string; hint: string };

/** Active staff → picker options, with their access level as the second line. */
export function peopleOptions(
  users: { id: string; name: string; role: string | null }[],
): TaskPersonOption[] {
  return users.map((person) => ({
    value: person.id,
    label: person.name,
    hint: isRoleId(person.role) ? ROLE_BY_ID[person.role].label : "",
  }));
}
