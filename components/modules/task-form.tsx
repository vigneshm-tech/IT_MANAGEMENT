"use client";

import Link from "next/link";
import { AlertCircle, CheckCircle2, Loader2 } from "lucide-react";
import { useActionState } from "react";
import { Button, buttonClass } from "@/components/ui/button";
import { ROLE_GROUPS, VISIBLE_ROLES } from "@/lib/roles";
import { ACTIVITY_TYPES, NEXT_TASK_ID_HINT, PLAN_STATUS_OPTIONS } from "@/lib/tasks/options";
import type { FormState } from "@/lib/forms";
import type { TaskRecord } from "@/lib/tasks/repository";
import { createTaskAction, updateTaskAction } from "@/app/(app)/modules/tasks/actions";

function Section({
  title,
  hint,
  children,
}: {
  title: string;
  hint?: string;
  children: React.ReactNode;
}) {
  return (
    <section className="border border-line bg-surface">
      <div className="border-b border-line px-4 py-3 sm:px-5">
        <h2 className="text-[12px] font-semibold uppercase tracking-[0.12em] text-navy">{title}</h2>
        {hint && <p className="mt-1 text-[11.5px] text-muted">{hint}</p>}
      </div>
      <div className="grid grid-cols-1 gap-x-5 gap-y-4 px-4 py-4 sm:grid-cols-2 sm:px-5">{children}</div>
    </section>
  );
}

function Full({ children, span = 2 }: { children: React.ReactNode; span?: 1 | 2 }) {
  return <div className={span === 2 ? "sm:col-span-2" : undefined}>{children}</div>;
}

function Feedback({ state }: { state: FormState }) {
  if (state.error) {
    return (
      <p
        role="alert"
        className="flex items-start gap-2 border border-[#eccfcd] bg-danger-soft px-3 py-2 text-[12.5px] text-danger"
      >
        <AlertCircle className="mt-0.5 h-3.5 w-3.5 shrink-0" aria-hidden />
        {state.error}
      </p>
    );
  }
  if (state.ok && state.message) {
    return (
      <p className="flex items-center gap-2 border border-[#cfe4d4] bg-success-soft px-3 py-2 text-[12.5px] text-success">
        <CheckCircle2 className="h-3.5 w-3.5" aria-hidden />
        {state.message}
      </p>
    );
  }
  return null;
}

/**
 * Full-page task form — no dialog. The requester is captured from the session,
 * the id is generated by the database, and the assignee list is grouped by team.
 */
export function TaskForm({
  mode,
  requester,
  clients,
  task,
}: {
  mode: "create" | "edit";
  requester: { name: string; email: string };
  clients: string[];
  task?: TaskRecord;
}) {
  const [state, formAction, pending] = useActionState(
    mode === "create" ? createTaskAction : updateTaskAction,
    {} as FormState,
  );

  const cancelHref = mode === "edit" && task ? `/modules/tasks/${task.id}` : "/modules/tasks";
  const roleGroups = Object.keys(ROLE_GROUPS) as (keyof typeof ROLE_GROUPS)[];

  return (
    <form action={formAction} className="space-y-4">
      {mode === "edit" && task && <input type="hidden" name="id" value={task.id} />}

      <Section title="Request">
        <div>
          <label htmlFor="task-id" className="field-label">
            Task ID
          </label>
          <input
            id="task-id"
            value={task?.id ?? NEXT_TASK_ID_HINT}
            readOnly
            className="field bg-[#f7f9fc] text-muted"
            aria-readonly
          />
        </div>

        <div>
          <label htmlFor="referenceTicketNo" className="field-label">
            Reference ticket no.
          </label>
          <input
            id="referenceTicketNo"
            name="referenceTicketNo"
            defaultValue={task?.referenceTicketNo ?? ""}
            placeholder="Portal ticket, e.g. 4821"
            className="field"
          />
        </div>

        <Full>
          <label htmlFor="title" className="field-label">
            Task name<span className="ml-0.5 text-danger">*</span>
          </label>
          <input
            id="title"
            name="title"
            required
            minLength={4}
            defaultValue={task?.title ?? ""}
            placeholder="What needs to happen?"
            className="field"
          />
        </Full>

        <Full>
          <label htmlFor="description" className="field-label">
            Task description
          </label>
          <textarea
            id="description"
            name="description"
            rows={3}
            defaultValue={task?.description ?? ""}
            placeholder="Context, scope and acceptance criteria"
            className="field resize-none"
          />
        </Full>

        <div>
          <label htmlFor="clientName" className="field-label">
            Client name
          </label>
          <input
            id="clientName"
            name="clientName"
            list="task-clients"
            defaultValue={task?.clientName ?? ""}
            placeholder={clients.length ? "Start typing a client" : "Client name"}
            className="field"
          />
          <datalist id="task-clients">
            {clients.map((client) => (
              <option key={client} value={client} />
            ))}
          </datalist>
        </div>

        <div>
          <label htmlFor="activityType" className="field-label">
            Activity type<span className="ml-0.5 text-danger">*</span>
          </label>
          <select
            id="activityType"
            name="activityType"
            required
            defaultValue={task?.activityType ?? ""}
            className="field"
          >
            <option value="">Select an activity</option>
            {ACTIVITY_TYPES.map((type) => (
              <option key={type} value={type}>
                {type}
              </option>
            ))}
          </select>
        </div>
      </Section>

      <Section title="Requested by" hint="Captured automatically from the signed-in account.">
        <div>
          <label htmlFor="requestedByName" className="field-label">
            Requested by
          </label>
          <input
            id="requestedByName"
            name="requestedByName"
            defaultValue={task?.requestedByName || requester.name}
            readOnly
            className="field bg-[#f7f9fc] text-muted"
            aria-readonly
          />
        </div>

        <div>
          <label htmlFor="requestedByEmail" className="field-label">
            Requester email
          </label>
          <input
            id="requestedByEmail"
            name="requestedByEmail"
            type="email"
            defaultValue={task?.requestedByEmail || requester.email}
            readOnly
            className="field bg-[#f7f9fc] text-muted"
            aria-readonly
          />
        </div>
      </Section>

      <Section title="Work">
        <Full>
          <label htmlFor="serverDetails" className="field-label">
            Server details
          </label>
          <textarea
            id="serverDetails"
            name="serverDetails"
            rows={2}
            defaultValue={task?.serverDetails ?? ""}
            placeholder="Hostnames, environment or asset tags"
            className="field resize-none"
          />
        </Full>

        <div>
          <label htmlFor="planStatus" className="field-label">
            Planned or unplanned<span className="ml-0.5 text-danger">*</span>
          </label>
          <select
            id="planStatus"
            name="planStatus"
            required
            defaultValue={task?.planStatus ?? "unplanned"}
            className="field"
          >
            {PLAN_STATUS_OPTIONS.map((option) => (
              <option key={option.value} value={option.value}>
                {option.label}
              </option>
            ))}
          </select>
        </div>

        <div>
          <label htmlFor="dueDate" className="field-label">
            Due date
          </label>
          <input
            id="dueDate"
            name="dueDate"
            type="date"
            defaultValue={task?.dueDate ? new Date(task.dueDate).toISOString().slice(0, 10) : ""}
            className="field"
          />
        </div>

        <Full>
          <label htmlFor="communication" className="field-label">
            Communication
          </label>
          <textarea
            id="communication"
            name="communication"
            rows={2}
            defaultValue={task?.communication ?? ""}
            placeholder="Who was informed, and through which channel"
            className="field resize-none"
          />
        </Full>

        <div>
          <label htmlFor="assigneeRole" className="field-label">
            Assigned to<span className="ml-0.5 text-danger">*</span>
          </label>
          <select
            id="assigneeRole"
            name="assigneeRole"
            required
            defaultValue={task?.assigneeRole ?? "l2_support_engineer"}
            className="field"
          >
            {roleGroups.map((group) => {
              const roles = VISIBLE_ROLES.filter((role) => role.group === group);
              if (roles.length === 0) return null;
              return (
                <optgroup key={group} label={ROLE_GROUPS[group].label}>
                  {roles.map((role) => (
                    <option key={role.id} value={role.id}>
                      {role.label}
                    </option>
                  ))}
                </optgroup>
              );
            })}
          </select>
        </div>

        <div>
          <label htmlFor="priority" className="field-label">
            Priority<span className="ml-0.5 text-danger">*</span>
          </label>
          <select
            id="priority"
            name="priority"
            required
            defaultValue={task?.priority ?? "medium"}
            className="field"
          >
            <option value="low">Low</option>
            <option value="medium">Medium</option>
            <option value="high">High</option>
            <option value="critical">Critical</option>
          </select>
        </div>
      </Section>

      <Feedback state={state} />

      <div className="flex flex-wrap items-center justify-end gap-2">
        <Link href={cancelHref} className={buttonClass({ variant: "secondary" })}>
          Cancel
        </Link>
        <Button type="submit" disabled={pending}>
          {pending && <Loader2 className="h-3.5 w-3.5 animate-spin" aria-hidden />}
          {mode === "create" ? "Create task" : "Save changes"}
        </Button>
      </div>
    </form>
  );
}
